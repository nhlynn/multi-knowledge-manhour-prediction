logger = logging.getLogger(__name__)


def _strip_legacy_workbook_bloat(wb: openpyxl.Workbook) -> None:
    """Strip orphaned Defined Names and External Links from ``wb``
    before it's ever saved.

    SGL Team's real internal template
    (``simple_resource/sgl_import_export_format.xlsx``) is an old
    corporate workbook that has accumulated thousands of "zombie"
    Defined Names and dozens of External Link references over years of
    copy-pasting between unrelated spreadsheets — none of them are
    used by any formula on either of this workbook's own two sheets
    ("詳細見積_マスタと予実比較" / "見積・金額サマリ"). ``openpyxl``
    preserves both verbatim on every load→save round-trip by default,
    so without this step every single SGL export (and the sanitized
    ``import/sgl/sgl_import_template.xlsx`` built by
    ``import/sgl/build_sample_template.py``) silently balloons in size
    and can trigger Excel's "we found a problem with some content"
    repair prompt on open, even though this module never touches
    those names/links itself.

    Safe to call unconditionally: a template that's already clean (0
    defined names, 0 external links) is a no-op. Only ever call this
    on the in-memory ``Workbook`` this module just loaded and is about
    to populate/save — never on ``template_path`` itself.
    """
    removed_names = len(wb.defined_names)
    removed_links = len(wb._external_links)
    if not removed_names and not removed_links:
        return
    wb.defined_names.clear()
    wb._external_links = []
    logger.info(
        "Stripped %d orphaned defined name(s) and %d external link(s) "
        "from SGL Team's export template before populating it.",
        removed_names, removed_links,
    )


_MAIN_HEADER_ROW = 2
_PHASE_LABEL_ROW = 3

_CATEGORY_HEADER = "区分"
_TASK_HEADER = "項目"
_PRIORITY_HEADER = "優先度/難易度"
_STATUS_HEADER = "ステータス"
_REMARKS_HEADER = "備考"
_WORK_DETAIL_HEADER = "作業詳細"
_PHASE_GROUP_HEADER = "工数（人時間）"
_TOTAL_HOURS_HEADER = "合計\n工数"
_TOTAL_AMOUNT_HEADER = "合計\n金額"

# Column B (no row-2 header text of its own) holds each labeled
# block's section heading on that block's own header row -- same fixed
# structural knowledge services/sgl_import_parser.py's own
# _BLOCK_LABEL_COL uses.
_BLOCK_LABEL_COL = 2

_SUMMARY_SHEET = "見積・金額サマリ"
_SUMMARY_TITLE_CELL = "A1"

# Matches any cell's own "=SUM(<col><row1>:<col><row2>)" formula --
# used to tell a genuine task row (a HORIZONTAL sum across that row's
# own phase-hour columns, e.g. "=SUM(H20:M20)" -- row1 == row2 == the
# row the formula itself is on) apart from a block's own subtotal row
# (a VERTICAL sum down a single column across several rows, e.g.
# "=SUM(N5:N6)" -- row1 != row2). Deliberately anchored/simple so it
# never matches the management-overhead/rollup rows' different formula
# shapes (e.g. "=N18", "=(SUM(N4,N7,N10,N14)*20%)", "=H4+H7+H10+H14").
_ROW_SUM_RE = re.compile(r"^=SUM\([A-Za-z]+(\d+):[A-Za-z]+(\d+)\)$")


class SglExportError(ValueError):
    """Raised when SGL Team's export template can't be built from, or
    the system data doesn't fit it -- see ``build_sgl_workbook``."""


def _resolve_header_columns(ws) -> dict[str, int]:
    """Map each row-2 header cell's (stripped) text to its 1-indexed
    column position."""
    return {
        str(cell.value).strip(): cell.column
        for cell in ws[_MAIN_HEADER_ROW]
        if cell.value is not None
    }


def _resolve_phase_columns(ws, phase_group_col: int) -> list[tuple[str, int]]:
    """Return ``[(phase_label, column_index), ...]`` for the phase
    sub-columns merged under the "工数（人時間）" header cell — same
    approach ``services/sgl_import_parser.py`` uses for import,
    reimplemented independently here so this module has no import-time
    dependency on that one beyond the shared ``SGL_SHEET_NAME`` constant.
    """
    end_col = phase_group_col
    for merged_range in ws.merged_cells.ranges:
        if merged_range.min_row == _MAIN_HEADER_ROW and merged_range.min_col == phase_group_col:
            end_col = merged_range.max_col
            break

    phase_columns = []
    for col in range(phase_group_col, end_col + 1):
        label = ws.cell(row=_PHASE_LABEL_ROW, column=col).value
        if label is not None and str(label).strip():
            phase_columns.append((str(label).strip(), col))
    return phase_columns


def _discover_writable_rows_by_block(
    ws, total_hours_col: int,
) -> tuple[dict[str, list[int]], list[int]]:
    """Discover every genuine task row in the sheet, grouped by which
    named block (column B's own section heading, e.g. "ユーザマスタ")
    it physically sits under -- unlike the old flat discovery, this
    lets ``build_sgl_workbook`` write each task back into ITS OWN
    block's rows, so a re-exported その他 task can never land under
    ユーザマスタ (or any other block) purely because of list-ordering.

    Returns ``(block_rows, unassigned_rows)``:

    - ``block_rows``: ``{block_label: [row, row, ...]}``, in row order,
      for every row covered by that block's own vertical subtotal
      formula (e.g. row 4's ``=SUM(N5:N6)`` -> block label read from
      B4, rows 5 and 6 both belong to it -- including a blank "buffer"
      row like row 6 that has no individual formula of its own, since
      the block's subtotal already accounts for it as real capacity).
    - ``unassigned_rows``: rows with their OWN single-row, horizontal
      ``=SUM(<col><row>:<col><row>)`` formula that are NOT covered by
      any block's subtotal range -- the template's "extra" overflow
      rows (rows 20–23 in the official template) provided for a
      project needing more task rows than the labeled blocks alone
      hold. Used as a shared fallback pool: for a task whose own block
      is full, or whose block can't be determined at all (e.g. data
      imported before ``block`` existed on the task record).

    Every management-overhead/rollup row's formula (``=N18``,
    ``=(SUM(N4,N7,N10,N14)*20%)``, ``=H4+H7+H10+H14``, ...) matches
    neither shape, so none of them is ever mistaken for a task row.
    """
    block_ranges: dict[int, tuple[int, int]] = {}  # header_row -> (start, end)
    self_formula_rows: set[int] = set()

    for row in range(4, ws.max_row + 1):
        formula = ws.cell(row=row, column=total_hours_col).value
        if not formula:
            continue
        match = _ROW_SUM_RE.match(str(formula))
        if not match:
            continue
        start_row, end_row = int(match.group(1)), int(match.group(2))
        if start_row == row and end_row == row:
            self_formula_rows.add(row)
        else:
            block_ranges[row] = (start_row, end_row)

    row_to_block: dict[int, str] = {}
    block_rows: dict[str, list[int]] = {}
    for header_row, (start_row, end_row) in block_ranges.items():
        label_val = ws.cell(row=header_row, column=_BLOCK_LABEL_COL).value
        label = str(label_val).strip() if label_val is not None and str(label_val).strip() else None
        if label is None:
            continue  # a subtotal range with no block label -- can't be targeted by name
        rows = list(range(start_row, end_row + 1))
        block_rows.setdefault(label, []).extend(rows)
        for r in rows:
            row_to_block[r] = label

    unassigned_rows = sorted(r for r in self_formula_rows if r not in row_to_block)
    for label in block_rows:
        block_rows[label].sort()

    return block_rows, unassigned_rows


def _phase_value(activities: list[dict[str, Any]], label: str) -> float:
    """Return the estimate_hours of the activity matching ``label``
    (whitespace/case-insensitive), or 0.0 if this task has none."""
    target = _normalize_header(label)
    for act in activities:
        if _normalize_header(act.get("task_detail") or "") == target:
            return _safe_float(act.get("estimate_hours"))
    return 0.0


def _ensure_row_totals(
    ws,
    row: int,
    phase_columns: list[tuple[str, int]],
    total_hours_col: int,
    total_amount_col: int | None,
) -> None:
    """Add this row's own 合計工数/合計金額 formulas if it doesn't
    already have one of its own (see the call site in
    ``build_sgl_workbook`` for why some discovered writable rows never
    had one to begin with).

    Mirrors the exact formula shape every other row in this template
    already uses -- ``=SUM(<first phase col><row>:<last phase
    col><row>)`` for 合計工数, and ``=(<col1><row>*S$3)+(<col2><row>*S$4)+...``
    for 合計金額, where each phase column's unit price lives in column S
    at a fixed row offset matching that phase's left-to-right position
    (要件定義→S3, 設計→S4, 開発→S5, テスト→S6, クラウド対応→S7,
    その他→S8) -- derived positionally from ``phase_columns`` rather
    than hardcoded, so a template with reordered/added/removed phase
    columns is still handled correctly.
    """
    existing = ws.cell(row=row, column=total_hours_col).value
    if existing:
        return  # this row already has its own formula -- never overwrite it

    first_letter = get_column_letter(phase_columns[0][1])
    last_letter = get_column_letter(phase_columns[-1][1])
    ws.cell(row=row, column=total_hours_col).value = f"=SUM({first_letter}{row}:{last_letter}{row})"

    if total_amount_col:
        terms = [
            f"({get_column_letter(col_idx)}{row}*S${3 + i})"
            for i, (_label, col_idx) in enumerate(phase_columns)
        ]
        ws.cell(row=row, column=total_amount_col).value = "=" + "+".join(terms)


def _set_cell(ws, row: int, col: int | None, value: Any) -> None:
    """Write ``value`` to (row, col), silently skipping a read-only
    ``MergedCell`` placeholder (a non-anchor position within a merged
    range, e.g. one block's 区分 merged across a multi-row task) -- the
    merge's own anchor cell already carries whatever single value the
    merge can hold; openpyxl raises ``AttributeError`` on writing to
    any other cell in that range.
    """
    if col is None:
        return
    cell = ws.cell(row=row, column=col)
    if isinstance(cell, MergedCell):
        return
    cell.value = value


def _populate_summary_title(wb, project_name: str | None) -> None:
    """Replace "見積・金額サマリ"'s sample project title (cell A1) with
    the current export's own Project Name, or blank if it was empty --
    mirrors ``services/bamawl_export_builder.py``'s
    ``_populate_req_definition_title`` exactly, for the same reason:
    the template's own literal sample text there has nothing to do
    with any particular export and must never leak into one.

    A missing "見積・金額サマリ" worksheet is not fatal -- logged and
    skipped.
    """
    if _SUMMARY_SHEET not in wb.sheetnames:
        logger.warning(
            "SGL Team's export template has no '%s' worksheet; skipping "
            "project title replacement.", _SUMMARY_SHEET,
        )
        return

    ws = wb[_SUMMARY_SHEET]
    ws[_SUMMARY_TITLE_CELL].value = project_name or None
    logger.info(
        "Set '%s'!%s to Project Name %r.", _SUMMARY_SHEET, _SUMMARY_TITLE_CELL, project_name or "",
    )


def build_sgl_workbook(
    filepath: str,
    categories: list[dict[str, Any]],
    template_path: str,
    project_name: str | None = None,
) -> None:
    """Populate SGL Team's own Excel template with Preview's data and
    save the result to ``filepath``.

    Only "詳細見積_マスタと予実比較" (every discovered task row) and
    "見積・金額サマリ"'s own title cell are ever written to -- no other
    cell in the workbook is touched.

    Args:
        filepath: Where to save the populated workbook (never
            ``template_path`` itself).
        categories: The Preview page's Category -> Task -> Activity
            data — the single source of truth for what's written.
            Every task across every category is one selected function;
            only these are exported, one per writable row, in the
            order Preview provides them. Nothing else -- no unselected
            function, no unrelated task, no leftover template sample
            data -- ends up in the result.
        template_path: Path to SGL Team's single official template
            workbook (``simple_resource/sgl_import_export_format.xlsx``).
        project_name: The Preview page's Project Name field, written
            into "見積・金額サマリ"'s title cell in place of the
            template's own sample text.

    Raises:
        SglExportError: if the template file/worksheet/columns can't
            be found or understood, or the project has more selected
            functions than the template's total writable-row capacity
            can hold.
    """
    if not os.path.isfile(template_path):
        raise SglExportError(f"SGL Team's export template file is missing: {template_path}")

    wb = openpyxl.load_workbook(template_path)
    _strip_legacy_workbook_bloat(wb)
    if SGL_SHEET_NAME not in wb.sheetnames:
        raise SglExportError(
            f"SGL Team's export template is missing the required '{SGL_SHEET_NAME}' worksheet."
        )
    ws = wb[SGL_SHEET_NAME]

    headers = _resolve_header_columns(ws)
    category_col = headers.get(_CATEGORY_HEADER)
    task_col = headers.get(_TASK_HEADER)
    priority_col = headers.get(_PRIORITY_HEADER)
    status_col = headers.get(_STATUS_HEADER)
    remarks_col = headers.get(_REMARKS_HEADER)
    work_detail_col = headers.get(_WORK_DETAIL_HEADER)
    phase_group_col = headers.get(_PHASE_GROUP_HEADER)
    total_hours_col = headers.get(_TOTAL_HOURS_HEADER)
    total_amount_col = headers.get(_TOTAL_AMOUNT_HEADER)

    if not (category_col and task_col and phase_group_col and total_hours_col):
        raise SglExportError(
            f"SGL Team's export template's required columns (区分/項目/工数（人時間）/合計工数) "
            f"could not all be located; cannot populate '{SGL_SHEET_NAME}'."
        )

    phase_columns = _resolve_phase_columns(ws, phase_group_col)
    if not phase_columns:
        raise SglExportError(
            f"SGL Team's export template's phase-hour columns could not be located; "
            f"cannot populate '{SGL_SHEET_NAME}'."
        )

    block_rows, unassigned_rows = _discover_writable_rows_by_block(ws, total_hours_col)
    all_writable_rows = sorted(set().union(*block_rows.values(), unassigned_rows)) \
        if block_rows or unassigned_rows else []
    if not all_writable_rows:
        raise SglExportError(
            f"SGL Team's export template has no recognizable task rows in "
            f"'{SGL_SHEET_NAME}'; cannot populate it."
        )
    capacity = len(all_writable_rows)

    tasks_with_category = [
        (cat.get("category", ""), task) for cat in categories for task in cat.get("tasks", [])
    ]
    if len(tasks_with_category) > capacity:
        raise SglExportError(
            f"This project has {len(tasks_with_category)} function(s), but SGL Team's export "
            f"template's '{SGL_SHEET_NAME}' worksheet only has room for {capacity} task rows -- "
            f"reduce the number of selected functions, or update the template."
        )

    # Assign each task to a row from its OWN block's pool first (the
    # block label recorded on the task at import time -- see
    # services/sgl_import_parser.py's own "block" field) -- so a
    # re-exported その他 task is written back under その他's rows, never
    # under ユーザマスタ or any other block, purely by list-ordering
    # coincidence. Only when a task's own block has no room left (or
    # its block is unknown/unrecognized, e.g. data imported before
    # this field existed) does it fall back to the template's shared
    # "extra" overflow rows (unassigned_rows) -- exactly the slack
    # capacity those unlabeled rows exist for. A task never spills
    # into a DIFFERENT named block's rows under any circumstance.
    block_pools = {label: list(rows) for label, rows in block_rows.items()}
    overflow_pool = list(unassigned_rows)
    assignments: list[tuple[str, dict[str, Any], int]] = []
    for category, task in tasks_with_category:
        task_block = str(task.get("block") or "").strip()
        pool = block_pools.get(task_block) if task_block else None
        if pool:
            row = pool.pop(0)
        elif overflow_pool:
            row = overflow_pool.pop(0)
        else:
            raise SglExportError(
                f"Function '{task.get('task', '')}' belongs to block "
                f"'{task_block or '(unknown)'}', but that block's rows are full and "
                f"SGL Team's export template's shared overflow rows are also full -- "
                f"reduce the number of selected functions, or update the template."
            )
        assignments.append((category, task, row))

    # Clear every writable row first (category/priority/status/task/
    # phase hours/remarks/作業詳細) -- so a row not used by this export's
    # selection can never retain the template's own sample data.
    # Column B's block labels, each block's own subtotal row, the
    # running row-number column, and every SUM/rate formula are never
    # touched.
    phase_col_indexes = [idx for _label, idx in phase_columns]
    for row in all_writable_rows:
        _set_cell(ws, row, category_col, None)
        _set_cell(ws, row, task_col, None)
        _set_cell(ws, row, priority_col, None)
        _set_cell(ws, row, status_col, None)
        _set_cell(ws, row, remarks_col, None)
        _set_cell(ws, row, work_detail_col, None)
        for col in phase_col_indexes:
            _set_cell(ws, row, col, None)

    for category, task, row in assignments:
        activities = task.get("activities", []) or []

        _set_cell(ws, row, category_col, category)
        _set_cell(ws, row, task_col, task.get("task", ""))
        remarks = task.get("remarks")
        if remarks:
            _set_cell(ws, row, remarks_col, str(remarks))
        work_detail = task.get("work_detail")
        if work_detail:
            _set_cell(ws, row, work_detail_col, str(work_detail))
        priority = task.get("priority")
        if priority:
            _set_cell(ws, row, priority_col, str(priority))
        status = task.get("status")
        if status:
            _set_cell(ws, row, status_col, str(status))

        # Every phase column on a populated row is deterministically
        # set to exactly what Preview provided for that phase, or
        # blank if this task has no matching activity -- never left as
        # a stale sample value from the template.
        for label, col_idx in phase_columns:
            value = _phase_value(activities, label)
            _set_cell(ws, row, col_idx, value or None)

        # Some "writable" rows (a block's own blank buffer capacity,
        # e.g. row 6 within a "=SUM(N5:N6)"-style block subtotal) were
        # never given their own per-row 合計工数/合計金額 formula in the
        # template -- they only ever counted toward the block's
        # subtotal by virtue of being blank (contributing 0). Writing a
        # task's hours into such a row without also adding its own
        # formula would silently leave that row's own total blank AND
        # undercount the block subtotal that sums it. Ensure every
        # POPULATED row has a working per-row formula, adding one only
        # if it doesn't already have one; a row's pre-existing formula
        # (e.g. row 20's own "=SUM(H20:M20)") is never overwritten.
        _ensure_row_totals(ws, row, phase_columns, total_hours_col, total_amount_col)

    _populate_summary_title(wb, project_name)

    wb.save(filepath)
    logger.info(
        "Built SGL Team export workbook: %s (%d selected function(s) written into '%s' only).",
        filepath, len(tasks_with_category), SGL_SHEET_NAME,
    )


class SglExportBuilder(BaseExportService):
    """SGL Team's export builder (Strategy Pattern) -- the single home
    for everything SGL-specific about exporting: the Strategy Pattern
    wiring (``build``) and where its official template lives
    (``template_path``).

    Unlike ``BamawlExportBuilder``/``KikanExportBuilder``, this has no
    ``resolve_column_mapping`` -- SGL's export doesn't use a
    DB-configured ``column_mapping`` at all (its row/column layout is
    discovered directly from the template itself, every time; see
    ``build_sgl_workbook``), so ``routes/export.py`` dispatches to this
    strategy unconditionally rather than gating on a seeded config row.
    """

    team_name = "SGL Team"

    @staticmethod
    def template_path(app_root_path: str) -> str:
        """Path to SGL Team's single official Excel template -- the
        same file Template Download serves and import validation
        accepts. There is deliberately no separate export-only
        template.
        """
        return os.path.join(app_root_path, "simple_resource", "sgl_import_export_format.xlsx")

    def build(self, context: ExportContext) -> None:
        build_sgl_workbook(
            context.filepath, context.categories, context.template_path, context.project_name,
        )