"""SGL Team's own Export Builder.

Independent from ``services/bamawl_export_builder.py`` and
``services/kikan_export_builder.py`` — no shared code between any of
them beyond the generic, team-agnostic helpers already in
``services/excel_parser.py``. Built directly on top of SGL Team's real
internal Excel workbook, ``simple_resource/sgl_import_export_format.xlsx``
-- export's base template, always (see ``utils/migrations/sgl_import_export_config.py``
for the full picture: Template Download and import validation instead
use a separate, sanitized public copy of this same workbook,
``import/sgl/sgl_import_template.xlsx``, generated by
``import/sgl/build_sample_template.py`` -- mirroring Bamawl Team's own
two-file design, not KiKan Team's single-file one). There is
deliberately no separate EXPORT-only template file, though: this
module always copies ``simple_resource/sgl_import_export_format.xlsx``
(``openpyxl.load_workbook`` reads it; ``wb.save`` writes to the export
path, never back to ``template_path``), populates the copy, and saves
the copy -- the sanitized public sample is never read here.

Design — genuinely different from Bamawl/KiKan, because SGL's own
"詳細見積_マスタと予実比較" worksheet is genuinely different from either of
theirs:

- Bamawl/KiKan populate one flat, appendable block of interchangeable
  function rows. SGL's worksheet instead scatters its writable task
  rows across the sheet, interleaved with block-subtotal rows (column
  B labels like "ユーザマスタ", each with its own vertical
  ``=SUM(N5:N6)``-style subtotal down a single column) and
  management-overhead/rollup rows (percentage- or addition-based
  formulas). A row counts as writable if it's either (a) covered by a
  block's own subtotal range (e.g. row 4's ``=SUM(N5:N6)`` claims rows
  5 AND 6, even though row 6 has no individual total formula of its
  own -- it's still real capacity the block's own subtotal already
  accounts for), or (b) has its OWN horizontal, single-row
  ``=SUM(H{row}:M{row})`` formula, which also catches the "extra"
  unlabeled rows the template provides beyond any labeled block (rows
  20–23 in the official template) for a project needing more task rows
  than the labeled blocks alone hold. Both are discovered directly
  from the template every time (never hardcoded row numbers), so a
  template edit that adds/removes/resizes rows is picked up
  automatically; missing either category was an earlier version's bug
  (rows silently left with whatever the template shipped, invisible to
  both the clear step and the write step).
- Every selected function (across all Preview categories, flattened in
  order) is written into that discovered row list sequentially --
  exactly the same "flatten tasks, fill a discovered fixed-capacity
  row list in order" approach ``services/kikan_export_builder.py``
  uses for its own single block. More selected functions than the
  template's total writable-row capacity raises ``SglExportError``
  with a clear, specific message, rather than silently dropping data
  or overflowing into a subtotal/rollup row.
- Every discovered writable row is cleared FIRST (区分, 項目,
  優先度/難易度, ステータス, every phase-hour column, 備考) before any
  selected function is written -- so a row not used by this export's
  selection can never retain the official template's own sample
  category/task/priority/status/hours/remarks. Only a row a selected
  function is actually written into gets new values; a row this export
  doesn't use is left blank, not stale.
- 優先度/難易度 and ステータス are written from a task's own
  ``priority``/``status`` fields when present -- captured at import
  time from ``詳細見積_マスタと予実比較``'s own same-named columns (see
  ``services/sgl_import_parser.py``) and carried through Preview/search
  generically, the same mechanism ``work_detail``/``block`` use. Both
  were previously resolved and cleared here but never actually
  written back (a real gap, not by design -- caught alongside
  ``services/bamawl_export_builder.py``'s analogous ``Status`` gap);
  and ``services/sgl_import_parser.py`` never captured either column
  into task data in the first place, so there was nothing to write
  even before this. Left blank only for a task with no such value
  (e.g. one added directly in Preview, never imported from a
  workbook).
- The other worksheet, "見積・金額サマリ", has its own literal sample
  project title in cell A1 (e.g. "サンプルチェック改修" in the shipped
  template) -- also unrelated data with nothing to do with any
  particular export, so it's replaced with the current export's own
  Project Name (mirroring exactly how
  ``services/bamawl_export_builder.py``'s ``_populate_req_definition_title``
  replaces its own template's sample title cell) rather than left
  as-is. No other cell on that worksheet is touched -- its own summary
  formulas (which read back from "詳細見積_マスタと予実比較") are
  untouched and simply recompute from whatever this export wrote there.
- Column B's block labels, each block's own subtotal row, the running
  row-number column, the 合計工数/合計金額 per-row formulas, the
  management-overhead/rollup rows, and the unrelated 作業項目/単価
  rate-legend columns are never touched -- so Total Man Hour is
  whatever the template's own existing formulas compute from exactly
  the selected functions' literal hours, automatically excluding
  anything not selected (cleared to blank).
- A cell that's a read-only ``MergedCell`` placeholder (e.g. one
  block's 区分 is merged across a multi-row task, such as C16:C17) is
  silently skipped rather than written to — the merge's own anchor
  cell already carries whatever single value the merge can hold;
  openpyxl forbids writing anywhere else in the merge, and the merge
  itself is never resized or removed.
"""

