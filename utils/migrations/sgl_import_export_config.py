"""SGL Team's official Excel import template — structural validation spec.

Registers "SGL Team" in ``services/team_template_registry.py`` (via
``_build_sgl_template_spec`` below) so an uploaded workbook is
strictly validated -- required worksheets present, and the
"詳細見積_マスタと予実比較" worksheet's header row matching column-by-column
and in order -- exactly the same validation Bamawl Team and KiKan Team
already get, via the same team-agnostic
``services/team_template_validator.py``.

Deliberately does NOT touch, import from, or duplicate anything in
``utils/migrations/bamawl_import_export_config.py`` or
``utils/migrations/kikan_import_export_config.py`` — this module is
entirely self-contained, matching this codebase's existing "no shared
per-team parser code" pattern (see ``services/team_template_registry.py``'s
own module docstring).

SGL's actual knowledge extraction does NOT go through this module's
``SGL_COLUMN_MAPPING`` at all -- the official worksheet's two-row
header (see ``services/sgl_import_parser.py``) can't be expressed as a
single ``header_row`` mapping the way Bamawl/KiKan's can, so SGL has
its own dedicated parser (``services/sgl_import_parser.py``),
registered in ``services/import_strategies.py`` and dispatched by team
name in ``services/embedding_service.py::process_excel_file`` --
completely independent of ``services/excel_parser.py``'s generic,
``column_mapping``-driven "phases mode". ``SGL_COLUMN_MAPPING`` exists
only to satisfy ``TeamTemplateSpec.column_mapping``'s (unused for SGL)
required field and ``services.team_template_validator.parse_team_template``'s
signature — nothing in the app's actual upload flow calls
``parse_team_template`` for any team today.

Two-file design (mirrors Bamawl Team's own, NOT KiKan's single-file
design): ``sample_template_path`` below --
``import/sgl/sgl_import_template.xlsx`` -- is a sanitized copy of the
real internal workbook, generated by ``import/sgl/build_sample_template.py``
(replacing real project/task text and hours with generic sample
values, structure/formulas/merges/formatting all otherwise identical).
Template Download serves this sanitized copy, and import validation
(this module's ``SGL_HEADER_ROW``/``SGL_DETAIL_HEADERS``, which
describe *structure* shared by both files) accepts an uploaded copy of
it. The real internal workbook,
``simple_resource/sgl_import_export_format.xlsx``, is never exposed
for download -- it's read only as ``build_sample_template.py``'s
source, and directly by ``services/sgl_export_builder.py`` as every
export's base template (a separate concern, per its own module
docstring: export always populates a copy of the *real* workbook, not
the sanitized public one, so a real customer's own exported data is
built on the actual template rather than sample placeholders).

This module intentionally does NOT seed a ``team_import_configs`` row
(no ``seed_sgl_import_export_config`` function) -- the
``team_import_configs``-based export column mapping is unused by SGL
(see ``SGL_COLUMN_MAPPING``'s own comment below) and out of scope here.
"""

from typing import Any

SGL_TEAM_NAME = "SGL Team"

# The official template's full worksheet list, in order -- used (via
# _build_sgl_template_spec below) by services/team_template_validator.py
# to validate that an uploaded workbook has every required sheet before
# import is attempted at all. "見積・金額サマリ" is never read as a
# knowledge source (see services/sgl_import_parser.py) but its presence
# is still part of what makes a workbook "the official SGL template".
SGL_REQUIRED_SHEET_NAMES: list[str] = [
    "見積・金額サマリ",
    "詳細見積_マスタと予実比較",
]

# The one worksheet ever read for SGL knowledge import.
SGL_HEADER_SHEET = "詳細見積_マスタと予実比較"

# SGL_HEADER_SHEET's real header row is row 2 -- "No."/"区分"/"項目"/
# "作業詳細"/... plus the merged "工数（人時間）" group label (which spans
# columns H:M; row 3 underneath holds each phase's own sub-label --
# 要件定義/設計/開発/テスト/クラウド対応/その他 -- see
# services/sgl_import_parser.py, which reads that second row directly).
# services/team_template_validator.py only checks a single header row,
# so this structural gate validates row 2 only -- still 19 exact
# column positions, more than enough to reject a wrong/foreign
# workbook or a reordered/renamed column outright. A phase sub-column
# under H:M that's missing or mislabeled on row 3 is instead caught by
# services/sgl_import_parser.py itself at import time (logged and
# skipped, never silently misattributed to the wrong phase).
SGL_HEADER_ROW = 2

# Verbatim, in order, read directly from row 2 -- identical in both
# simple_resource/sgl_import_export_format.xlsx and the sanitized
# import/sgl/sgl_import_template.xlsx built from it (sanitization only
# ever replaces data-row values, never structure/headers). None marks
# a blank cell (either genuinely empty, e.g. column B, or a non-anchor
# position within the merged "工数（人時間）" H:M header -- merged cells
# only carry a value on their top-left/anchor cell).
SGL_DETAIL_HEADERS: list[Any] = [
    "No.", None, "区分", "項目", "作業詳細", "優先度/難易度", "ステータス",
    "工数（人時間）", None, None, None, None, None,
    "合計\n工数", "合計\n金額", "備考", None, "作業項目", "単価",
]

# Optional template-version marker: not configured, same as every other
# team today -- a documented no-op in
# services/team_template_validator.py::validate_team_template while
# this is None.
SGL_TEMPLATE_VERSION: str | None = None

# Unused by SGL's actual import (see module docstring) -- present only
# because TeamTemplateSpec.column_mapping has no default. Deliberately
# NOT a "phases mode" dict (no "phase_columns" key): SGL must never be
# accidentally routed through services/excel_parser.py's generic
# phases-mode reader, which assumes a single header row and would
# mis-locate SGL's row-3 phase sub-labels as "Unnamed: N" columns.
SGL_COLUMN_MAPPING: dict[str, Any] = {
    "sheet": SGL_HEADER_SHEET,
    "header_row": SGL_HEADER_ROW,
}


def _build_sgl_template_spec() -> Any:
    from services.team_template_validator import TeamTemplateSpec

    return TeamTemplateSpec(
        team_name=SGL_TEAM_NAME,
        required_sheet_names=SGL_REQUIRED_SHEET_NAMES,
        header_sheet=SGL_HEADER_SHEET,
        header_row=SGL_HEADER_ROW,
        expected_headers=SGL_DETAIL_HEADERS,
        column_mapping=SGL_COLUMN_MAPPING,
        template_version=SGL_TEMPLATE_VERSION,
        sample_template_path=("import", "sgl", "sgl_import_template.xlsx"),
    )
