"""SSD Team's official Excel import template — structural validation spec.

Registers "SSD Team" in ``services/team_template_registry.py`` (via
``_build_ssd_template_spec`` below) so an uploaded workbook is strictly
validated — required worksheets present, and the
"詳細設計～システムテスト 本番移行" worksheet's field-header row matching
column-by-column and in order — exactly the same validation Bamawl,
KiKan, and SGL Teams already get, via the same team-agnostic
``services/team_template_validator.py``.

Deliberately self-contained: it does NOT touch, import from, or
duplicate anything in the Bamawl/KiKan/SGL config modules — matching
this codebase's existing "no shared per-team parser code" pattern (see
``services/team_template_registry.py``'s own module docstring).

SSD's actual knowledge extraction does NOT go through this module's
``SSD_COLUMN_MAPPING`` at all — the official worksheet's THREE-row
header and its VLOOKUP-driven standard-hours columns (see
``services/ssd_import_parser.py``) can't be expressed as a single
``header_row`` mapping the way Bamawl/KiKan's can, so SSD has its own
dedicated parser, registered in ``services/import_strategies.py`` and
dispatched by team name in
``services/embedding_service.py::process_excel_file`` — completely
independent of ``services/excel_parser.py``'s generic,
``column_mapping``-driven "phases mode". ``SSD_COLUMN_MAPPING`` exists
only to satisfy ``TeamTemplateSpec.column_mapping``'s required field
and ``parse_team_template``'s signature; nothing in the app's actual
upload flow calls ``parse_team_template`` for any team today.

Two-file design (mirrors Bamawl/SGL's own, NOT KiKan's single-file
design): ``sample_template_path`` below —
``import/ssd/ssd_import_template.xlsx`` — is a sanitized copy of the
real internal workbook, generated by
``import/ssd/build_sample_template.py`` (replacing real project/task
text and hours with generic sample values; structure, formulas, merges
and formatting all otherwise identical). Template Download serves this
sanitized copy, and import validation (this module's
``SSD_HEADER_ROW``/``SSD_DETAIL_HEADERS``, which describe *structure*
shared by both files) accepts an uploaded copy of it. The real
internal workbook, ``simple_resource/ssd_import_export_format.xlsx``,
is never exposed for download — it's read only as
``build_sample_template.py``'s source, and directly by
``services/ssd_export_builder.py`` as every export's base template.
"""

from typing import Any

SSD_TEAM_NAME = "SSD Team"

# The official template's full worksheet list, in order — used (via
# _build_ssd_template_spec below) by services/team_template_validator.py
# to validate that an uploaded workbook has every required sheet before
# import is attempted at all. Only the detail sheet(s) and the lookup
# sheet are ever READ for knowledge (see services/ssd_import_parser.py),
# but every sheet's presence is part of what makes a workbook "the
# official SSD template". "詳細設計～システムテスト 本番移行_2" (the second
# proposal option) is intentionally NOT required — a project with a
# single proposal ships without it, and the parser reads it only when
# present.
SSD_REQUIRED_SHEET_NAMES: list[str] = [
    "シート説明",
    "見積総額",
    "対応方針",
    "前提条件",
    "システム構成図",
    "詳細設計～システムテスト 本番移行",
    "難易度別標準工数",
    "体制",
    "成果物",
    "スケジュール",
]

# The primary worksheet read for SSD knowledge import.
SSD_HEADER_SHEET = "詳細設計～システムテスト 本番移行"

# SSD_HEADER_SHEET's field-header row is row 5 — "No"/"機能名"/"機能概要"/
# "要件（ユースケース）"/"難易度"/"新規/改定"/"見積根拠" plus three merged group
# labels ("標準作業工数（人日）" J:M, "調整工数（人日）" N:Q, "見積工数（人日）"
# R:U). Rows 6 and 7 hold sub-group and phase sub-labels underneath
# them (要件定義-style breakdown), read directly by
# services/ssd_import_parser.py. services/team_template_validator.py
# only checks a single header row, so this structural gate validates
# row 5 only — still many exact column positions, enough to reject a
# wrong/foreign workbook or a reordered/renamed field column outright.
# A phase sub-column mislabeled on row 7 is instead handled by the
# parser at import time (resolved from the merge span, never silently
# misattributed).
SSD_HEADER_ROW = 5

# Verbatim, in order, read directly from row 5 of the official
# template. None marks a blank cell — either genuinely empty (column A,
# and the trailing columns past 備考) or a non-anchor position within a
# merged group-label span (merged cells carry a value only on their
# top-left/anchor cell, so J holds "標準作業工数（人日）" while K/L/M are
# None, etc.).
SSD_DETAIL_HEADERS: list[Any] = [
    None, "No", "機能名", "機能概要", "要件（ユースケース）", "難易度",
    "新規/改定", "見積根拠", None, "標準作業工数（人日）", None, None, None,
    "調整工数（人日）", None, None, None, "見積工数（人日）", None, None, None,
    "備考", None, None, None, None,
]

# Optional template-version marker: not configured, same as every other
# team today — a documented no-op in
# services/team_template_validator.py::validate_team_template while
# this is None.
SSD_TEMPLATE_VERSION: str | None = None

# Unused by SSD's actual import (see module docstring) — present only
# because TeamTemplateSpec.column_mapping has no default. Deliberately
# NOT a "phases mode" dict (no "phase_columns" key): SSD must never be
# accidentally routed through services/excel_parser.py's generic
# phases-mode reader, which assumes a single header row and would
# mis-locate SSD's three-row header and VLOOKUP columns entirely.
SSD_COLUMN_MAPPING: dict[str, Any] = {
    "sheet": SSD_HEADER_SHEET,
    "header_row": SSD_HEADER_ROW,
}


def _build_ssd_template_spec() -> Any:
    from services.team_template_validator import TeamTemplateSpec

    return TeamTemplateSpec(
        team_name=SSD_TEAM_NAME,
        required_sheet_names=SSD_REQUIRED_SHEET_NAMES,
        header_sheet=SSD_HEADER_SHEET,
        header_row=SSD_HEADER_ROW,
        expected_headers=SSD_DETAIL_HEADERS,
        column_mapping=SSD_COLUMN_MAPPING,
        template_version=SSD_TEMPLATE_VERSION,
        sample_template_path=("import", "ssd", "ssd_import_template.xlsx"),
    )